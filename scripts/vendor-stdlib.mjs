// @stdlib の分布関数を単一のESMファイルにまとめる。
// @stdlib は1関数あたり数百ファイルに分かれており、WSL の /mnt 配下などでは読み込みが極端に遅いため、
// 生成物（src/vendor/stdlib.js）をリポジトリに含めて利用する。依存を更新したら `npm run vendor` で再生成する。
import { build } from 'esbuild';

await build({
  entryPoints: ['scripts/stdlib-entry.js'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  minify: true,
  legalComments: 'eof',
  outfile: 'src/vendor/stdlib.js',
  banner: { js: '/* Generated by scripts/vendor-stdlib.mjs from @stdlib packages (Apache-2.0). Do not edit. */' },
});
console.log('src/vendor/stdlib.js を生成しました');
